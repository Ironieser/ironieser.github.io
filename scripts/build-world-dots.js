/**
 * Build the land dot grid for the footer visitor map from the vendored world map.
 *
 * Usage:  node scripts/build-world-dots.js
 * Input:  assets/js/vendor/echarts-world.js (Natural Earth 110m, ISO-2 names)
 * Output: assets/js/vendor/world-dots.js
 *
 * The grid is equirectangular, STEP degrees per cell, cropped to LAT_TOP..LAT_BOT
 * (Antarctica dropped). Each land cell is assigned to the country containing its
 * center; cells are stored per country as base-36 indices (row * cols + col).
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets/js/vendor/echarts-world.js');
const OUT = path.join(ROOT, 'assets/js/vendor/world-dots.js');

const STEP = 2.6;
const LAT_TOP = 84;
const LAT_BOT = -56;

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(SRC, 'utf8'), sandbox);
const features = sandbox.window.__ECHARTS_WORLD__.features.filter((f) => f.properties.name !== 'AQ');

const polys = (f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates);

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const boxes = features.map((f) => {
  let minX = 180, maxX = -180, minY = 90, maxY = -90;
  polys(f).forEach((p) => p[0].forEach(([x, y]) => {
    minX = Math.min(minX, x); maxX = Math.max(maxX, x);
    minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }));
  return { f, minX, maxX, minY, maxY };
});

const cols = Math.ceil(360 / STEP);
const rows = Math.ceil((LAT_TOP - LAT_BOT) / STEP);
const byCountry = {};
let total = 0;

for (let row = 0; row < rows; row++) {
  const lat = LAT_TOP - STEP * (row + 0.5);
  for (let col = 0; col < cols; col++) {
    const lon = -180 + STEP * (col + 0.5);
    for (const b of boxes) {
      if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
      const hit = polys(b.f).some((p) => inRing(lon, lat, p[0]) && !p.slice(1).some((hole) => inRing(lon, lat, hole)));
      if (hit) {
        const code = b.f.properties.name;
        (byCountry[code] = byCountry[code] || []).push((row * cols + col).toString(36));
        total++;
        break;
      }
    }
  }
}

const data = { step: STEP, latTop: LAT_TOP, cols, rows, countries: {} };
Object.keys(byCountry).sort().forEach((code) => { data.countries[code] = byCountry[code].join(','); });

fs.writeFileSync(OUT, '/* Generated by scripts/build-world-dots.js; do not edit. */\nwindow.__WORLD_DOTS__=' + JSON.stringify(data) + ';\n');
console.log(`${total} land dots in ${cols}x${rows} grid, ${Object.keys(byCountry).length} countries -> ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
